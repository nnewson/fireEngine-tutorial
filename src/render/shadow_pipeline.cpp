/** @cond INTERNAL */
/* --- Internal member functions --- */

ShadowPipeline::ShadowPipeline(const Device& device, PipelineDescription description,
                               vk::Format depthFormat)
    : description_{description}
{
    descriptorSetLayout_ = createPushDescriptorLayout(device.logicalDevice());
    pipelineLayout_ = createPipelineLayout(device.logicalDevice(), descriptorSetLayout_);
    pipeline_ =
        createDepthOnlyPipeline(device.logicalDevice(), pipelineLayout_, description_, depthFormat);
}

const vk::raii::PipelineLayout& ShadowPipeline::pipelineLayout() const noexcept
{
    return pipelineLayout_;
}

const vk::raii::Pipeline& ShadowPipeline::pipeline() const noexcept
{
    return pipeline_;
}

const PipelineDescription& ShadowPipeline::description() const noexcept
{
    return description_;
}
