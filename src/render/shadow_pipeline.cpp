/** @brief Compiled depth-only Slang module generated by the shader target. */
constexpr std::string_view kShadowShaderPath = FIRE_ENGINE_SHADER_DIRECTORY "/shadow.spv";

/** @brief Preserved SPIR-V entry-point name of the only shader stage. */
constexpr const char* kVertexEntryPoint = "vertexMain";

/** @brief Shared frame-uniform buffer consumed by the shadow vertex stage. */
constexpr vk::DescriptorSetLayoutBinding kFrameUniformBinding{
    .binding = 0,
    .descriptorType = vk::DescriptorType::eUniformBuffer,
    .descriptorCount = 1,
    .stageFlags = vk::ShaderStageFlagBits::eVertex,
};

/** @brief Position is the shadow vertex stage's only consumed attribute. */
constexpr vk::VertexInputAttributeDescription kPositionAttribute{
    .location = 0,
    .binding = 0,
    .format = vk::Format::eR32G32B32Sfloat,
    .offset = static_cast<std::uint32_t>(offsetof(Vertex, position)),
};

/** @brief Per-frame viewport, scissor, and depth bias are recorded dynamically. */
constexpr std::array kDynamicStates = {
    vk::DynamicState::eViewport,
    vk::DynamicState::eScissor,
    vk::DynamicState::eDepthBias,
};

