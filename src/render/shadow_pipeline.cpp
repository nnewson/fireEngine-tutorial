/**
 * @brief Maps one shared vertex layout to the position consumed by the shadow stage.
 * @param vertexLayout Layout selected by the shared pipeline description.
 * @return Position attribute within the shared interleaved binding.
 */
[[nodiscard]] const vk::VertexInputAttributeDescription&
compilePositionAttribute(VertexLayoutKey vertexLayout)
{
    switch (vertexLayout)
    {
    case VertexLayoutKey::ePositionColorTextureCoordinate:
        return kPositionAttribute;
    }
    throw std::invalid_argument("Pipeline description contains an unsupported vertex layout");
}

/**
 * @brief Creates set zero as a one-binding Vulkan push-descriptor layout.
 * @param device Logical device that owns the descriptor-set layout.
 * @return Layout accepting the shared frame-uniform buffer in the vertex stage.
 */
[[nodiscard]] vk::raii::DescriptorSetLayout
createPushDescriptorLayout(const vk::raii::Device& device)
{
    const vk::DescriptorSetLayoutCreateInfo createInfo{
        .flags = vk::DescriptorSetLayoutCreateFlagBits::ePushDescriptor,
        .bindingCount = 1,
        .pBindings = &kFrameUniformBinding,
    };
    return {device, createInfo};
}

/**
 * @brief Creates the uniform and model-transform interface used by the shadow shader.
 * @param device Logical device that owns the pipeline layout.
 * @param descriptorSetLayout Push-descriptor layout installed at set zero.
 * @return Pipeline layout containing one set layout and one vertex push-constant range.
 */
[[nodiscard]] vk::raii::PipelineLayout
createPipelineLayout(const vk::raii::Device& device,
                     const vk::raii::DescriptorSetLayout& descriptorSetLayout)
{
    const vk::DescriptorSetLayout layout = *descriptorSetLayout;
    constexpr vk::PushConstantRange drawConstants{
        .stageFlags = vk::ShaderStageFlagBits::eVertex,
        .offset = 0,
        .size = sizeof(ShadowDrawConstants),
    };
    const vk::PipelineLayoutCreateInfo createInfo{
        .setLayoutCount = 1,
        .pSetLayouts = &layout,
        .pushConstantRangeCount = 1,
        .pPushConstantRanges = &drawConstants,
    };
    return {device, createInfo};
}

/**
 * @brief Creates a depth-only dynamic-rendering graphics pipeline.
 * @param device Logical device that owns the pipeline.
 * @param pipelineLayout Layout shared with future shadow recording commands.
 * @param description Shared mesh-layout requirement mapped into vertex input state.
 * @param depthFormat Sampled shadow-map format used by dynamic rendering.
 * @return Pipeline with one vertex stage and no color or fragment state.
 */
[[nodiscard]] vk::raii::Pipeline
createDepthOnlyPipeline(const vk::raii::Device& device,
                        const vk::raii::PipelineLayout& pipelineLayout,
                        PipelineDescription description, vk::Format depthFormat)
{
    const vk::VertexInputBindingDescription& vertexBinding =
        compileVertexBinding(description.vertexLayout);
    const vk::VertexInputAttributeDescription& positionAttribute =
        compilePositionAttribute(description.vertexLayout);
    const std::vector<std::uint32_t> shaderCode = detail::loadSpirv(kShadowShaderPath);
    const vk::ShaderModuleCreateInfo moduleInfo{
        .codeSize = shaderCode.size() * sizeof(std::uint32_t),
        .pCode = shaderCode.data(),
    };
    const vk::StructureChain vertexStage{
        vk::PipelineShaderStageCreateInfo{
            .stage = vk::ShaderStageFlagBits::eVertex,
            .module = nullptr,
            .pName = kVertexEntryPoint,
        },
        moduleInfo,
    };
    const vk::PipelineShaderStageCreateInfo shaderStage =
        vertexStage.get<vk::PipelineShaderStageCreateInfo>();
    const vk::PipelineVertexInputStateCreateInfo vertexInput{
        .vertexBindingDescriptionCount = 1,
        .pVertexBindingDescriptions = &vertexBinding,
        .vertexAttributeDescriptionCount = 1,
        .pVertexAttributeDescriptions = &positionAttribute,
    };
    const vk::PipelineInputAssemblyStateCreateInfo inputAssembly{
        .topology = vk::PrimitiveTopology::eTriangleList,
    };
    const vk::PipelineViewportStateCreateInfo viewportState{
        .viewportCount = 1,
        .scissorCount = 1,
    };
    const vk::PipelineRasterizationStateCreateInfo rasterization{
        .polygonMode = vk::PolygonMode::eFill,
        // The shadow recorder uses the same negative-height viewport as the
        // forward pass, preserving this winding and culling convention.
        .cullMode = vk::CullModeFlagBits::eBack,
        .frontFace = vk::FrontFace::eCounterClockwise,
        .depthBiasEnable = vk::True,
        .lineWidth = 1.0F,
    };
    const vk::PipelineMultisampleStateCreateInfo multisampling{
        .rasterizationSamples = vk::SampleCountFlagBits::e1,
    };
    const vk::PipelineDepthStencilStateCreateInfo depthStencil{
        .depthTestEnable = vk::True,
        .depthWriteEnable = vk::True,
        .depthCompareOp = vk::CompareOp::eLess,
    };
    const vk::PipelineColorBlendStateCreateInfo colorBlending{};
    const vk::PipelineDynamicStateCreateInfo dynamicState{
        .dynamicStateCount = static_cast<std::uint32_t>(kDynamicStates.size()),
        .pDynamicStates = kDynamicStates.data(),
    };
    const vk::StructureChain pipelineCreateChain{
        vk::GraphicsPipelineCreateInfo{
            .stageCount = 1,
            .pStages = &shaderStage,
            .pVertexInputState = &vertexInput,
            .pInputAssemblyState = &inputAssembly,
            .pViewportState = &viewportState,
            .pRasterizationState = &rasterization,
            .pMultisampleState = &multisampling,
            .pDepthStencilState = &depthStencil,
            .pColorBlendState = &colorBlending,
            .pDynamicState = &dynamicState,
            .layout = *pipelineLayout,
        },
        vk::PipelineRenderingCreateInfo{
            .depthAttachmentFormat = depthFormat,
        },
    };
    return {device, nullptr, pipelineCreateChain.get<vk::GraphicsPipelineCreateInfo>()};
}
